    /**
     * Maneja el evento de clic en el botón "Modificar". 
     * Valida los datos actuales del formulario y llama al DAO para actualizar 
     * el registro correspondiente al ID seleccionado.
     * 
     * @param evt Objeto de evento de acción.
     */
    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        
        if (idPeliculaseleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona una película de la tabla para modificar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            String titulo = txtTitulo.getText().trim();
            String director = txtDirector.getText().trim();
            String estreno = txtEstreno.getText().trim();
            String duracionStr = txtDuracion.getText().trim();
            String clasificacion = txtClasificacion.getText().trim();

            if (titulo.isEmpty() || director.isEmpty() || estreno.isEmpty() || duracionStr.isEmpty() || clasificacion.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Error de validación", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            int duracion;
            try {
                duracion = Integer.parseInt(duracionStr);
                if (duracion <= 0) throw new NumberFormatException();
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "La duración debe ser un número entero positivo.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            boolean exito = PeliculaDAO.actualizarPelicula(idPeliculaseleccionada, titulo, director, estreno, duracion, clasificacion);

            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "Película modificada con éxito.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
                PeliculaDAO.cargarTabla(tblPeliculas);
                btnLimpiarActionPerformed(evt);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo modificar la película. Revisa los datos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage(), "Error crítico", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnModificarActionPerformed

