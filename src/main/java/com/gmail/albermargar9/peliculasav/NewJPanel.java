    /**
     * Maneja el evento de clic en el botón "Eliminar". 
     * Valida la selección, pide confirmación al usuario y llama al DAO para borrar el registro.
     * 
     * @param evt Objeto de evento de acción.
     */
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idPeliculaseleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona una película de la tabla para eliminarla.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
    
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
            "¿Estás seguro de que deseas eliminar esta película?\nEsta acción no se puede deshacer.", 
            "Confirmar Eliminación", 
            javax.swing.JOptionPane.YES_NO_OPTION, 
            javax.swing.JOptionPane.WARNING_MESSAGE);
            
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            boolean exito = PeliculaDAO.eliminarPelicula(idPeliculaseleccionada);
        
            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "Película eliminada con éxito.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
                PeliculaDAO.cargarTabla(tblPeliculas);
            
                btnLimpiarActionPerformed(evt);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo eliminar la película. Revisa la conexión.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

